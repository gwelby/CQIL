/**
 * Initialize the Tone.js audio system for frequency playback
 */
function initToneSystem() {
  // Create a polyphonic synth for rich harmonics
  synth = new Tone.PolySynth(Tone.Synth).toDestination();
  synth.volume.value = -20; // Start with lower volume
  
  // Set initial parameters for 432 Hz ground state
  synth.set({
    envelope: {
      attack: 0.5,
      decay: 0.5,
      sustain: 1.0,
      release: 2.0
    }
  });
}

/**
 * Setup frequency navigation between different states
 */
function setupFrequencyNavigation() {
  // Get navigation elements
  const navItems = document.querySelectorAll('.frequency-navigation li');
  const navButtons = document.querySelectorAll('.nav-button');
  
  // Add click handlers to frequency navigation
  navItems.forEach(item => {
    item.addEventListener('click', () => {
      const frequency = parseInt(item.getAttribute('data-frequency'), 10);
      changeFrequency(frequency);
    });
  });
  
  // Add click handlers to next/prev buttons
  navButtons.forEach(button => {
    button.addEventListener('click', () => {
      if (button.classList.contains('next')) {
        const nextFreq = parseInt(button.getAttribute('data-next'), 10);
        if (nextFreq) changeFrequency(nextFreq);
      } else if (button.classList.contains('prev')) {
        const prevFreq = parseInt(button.getAttribute('data-prev'), 10);
        if (prevFreq) changeFrequency(prevFreq);
      }
    });
  });
}

/**
 * Change to a different frequency state
 * @param {number} frequency - The target frequency
 */
function changeFrequency(frequency) {
  if (!FREQUENCIES[Object.keys(FREQUENCIES).find(key => FREQUENCIES[key] === frequency)]) {
    console.error(`Invalid frequency: ${frequency} Hz`);
    return;
  }
  
  // Stop any running practice
  if (practiceInterval) {
    clearInterval(practiceInterval);
    practiceInterval = null;
    
    // Reset practice button
    const practiceButton = document.querySelector('.start-practice');
    if (practiceButton) {
      practiceButton.textContent = 'Begin Practice';
      practiceButton.classList.remove('active');
    }
  }
  
  // Update UI state
  document.body.setAttribute('data-frequency', frequency);
  
  // Update navigation
  const navItems = document.querySelectorAll('.frequency-navigation li');
  navItems.forEach(item => {
    const itemFreq = parseInt(item.getAttribute('data-frequency'), 10);
    if (itemFreq === frequency) {
      item.classList.add('active');
    } else {
      item.classList.remove('active');
    }
  });
  
  // Update content sections
  const contentSections = document.querySelectorAll('.frequency-content');
  contentSections.forEach(section => {
    section.classList.add('hidden');
  });
  
  const targetSection = document.getElementById(`content-${frequency}`);
  if (targetSection) {
    targetSection.classList.remove('hidden');
    
    // If section is empty, load content dynamically
    if (targetSection.querySelector('.loading-indicator')) {
      loadFrequencyContent(frequency, targetSection);
    }
  }
  
  // Update frequency indicator
  const freqIndicator = document.querySelector('.frequency-indicator .current-frequency');
  if (freqIndicator) {
    freqIndicator.textContent = frequency;
  }
  
  const freqLabel = document.querySelector('.frequency-indicator .frequency-label');
  if (freqLabel) {
    const freqData = frequencyContent[frequency];
    freqLabel.textContent = freqData ? freqData.state : '';
  }
  
  // Play the frequency
  playFrequency(frequency, 2);
  
  // Update document background color with transition
  const freqData = frequencyContent[frequency];
  if (freqData && freqData.color) {
    document.documentElement.style.setProperty('--frequency-color', freqData.color);
  }
  
  // Update current frequency
  currentFrequency = frequency;
  
  console.log(`🔄 Shifted to ${frequency} Hz (${frequencyContent[frequency]?.state || 'Unknown'} state)`);
}

