/**
 * Setup practice timer functionality
 */
function setupPracticeTimers() {
  const practiceButtons = document.querySelectorAll('.start-practice');
  
  practiceButtons.forEach(button => {
    button.addEventListener('click', () => {
      // Find the closest timer element
      const timerContainer = button.closest('.practice-timer');
      if (!timerContainer) return;
      
      const timerElement = timerContainer.querySelector('.timer');
      if (!timerElement) return;
      
      // Get current time text and parse minutes
      const timeText = timerElement.textContent;
      const minutes = parseInt(timeText.split(':')[0], 10);
      
      togglePractice(minutes);
    });
  });
}

/**
 * Toggle practice session on/off
 * @param {number} minutes - Practice duration in minutes
 */
function togglePractice(minutes) {
  const practiceButton = document.querySelector('.start-practice');
  if (!practiceButton) return;
  
  const timerElement = document.querySelector('.timer');
  if (!timerElement) return;
  
  // If practice is running, stop it
  if (practiceInterval) {
    clearInterval(practiceInterval);
    practiceInterval = null;
    practiceButton.textContent = 'Begin Practice';
    practiceButton.classList.remove('active');
    timerElement.textContent = `${minutes}:00`;
    return;
  }
  
  // Start new practice
  let secondsRemaining = minutes * 60;
  
  // Update button state
  practiceButton.textContent = 'Stop Practice';
  practiceButton.classList.add('active');
  
  // Start continuous tone at current frequency
  playFrequency(currentFrequency, 0, true);
  
  // Start timer
  practiceInterval = setInterval(() => {
    secondsRemaining--;
    
    if (secondsRemaining <= 0) {
      // Practice complete
      clearInterval(practiceInterval);
      practiceInterval = null;
      practiceButton.textContent = 'Begin Practice';
      practiceButton.classList.remove('active');
      timerElement.textContent = `${minutes}:00`;
      
      // Stop tone
      stopFrequency();
      
      // Play completion tone
      playCompletionTone();
      return;
    }
    
    // Update timer display
    const displayMinutes = Math.floor(secondsRemaining / 60);
    const displaySeconds = secondsRemaining % 60;
    timerElement.textContent = `${displayMinutes}:${displaySeconds.toString().padStart(2, '0')}`;
    
  }, 1000);
}

/**
 * Play a frequency tone
 * @param {number} frequency - Frequency in Hz
 * @param {number} duration - Duration in seconds (0 for continuous)
 * @param {boolean} continuous - Whether to play continuously
 */
function playFrequency(frequency, duration = 2, continuous = false) {
  // Ensure Tone.js is started
  if (Tone.context.state !== 'running') {
    Tone.start();
  }
  
  // Stop any previous tone
  stopFrequency();
  
  // Set parameters based on frequency
  let attack, decay, sustain, release;
  
  switch (frequency) {
    case FREQUENCIES.GROUND:
      attack = 0.5; decay = 0.5; sustain = 1.0; release = 2.0;
      break;
    case FREQUENCIES.CREATION:
      attack = 0.3; decay = 0.6; sustain = 0.8; release = 1.5;
      break;
    case FREQUENCIES.HEART:
      attack = 0.2; decay = 0.8; sustain = 0.9; release = 2.5;
      break;
    case FREQUENCIES.VOICE:
      attack = 0.1; decay = 0.4; sustain = 0.7; release = 1.2;
      break;
    case FREQUENCIES.VISION:
      attack = 0.05; decay = 0.3; sustain = 0.6; release = 2.0;
      break;
    case FREQUENCIES.UNITY:
      attack = 0.01; decay = 0.2; sustain = 1.0; release = 3.0;
      break;
    default:
      attack = 0.1; decay = 0.5; sustain = 0.5; release = 1.0;
  }
  
  // Configure synth
  synth.set({
    envelope: { attack, decay, sustain, release }
  });
  
  // For practice sessions, we use a more complex harmonic structure
  if (continuous) {
    // Play fundamental
    synth.triggerAttack([frequency], Tone.now());
    
    // For resonant practices, add phi-harmonics
    if (frequency === FREQUENCIES.HEART || frequency === FREQUENCIES.UNITY) {
      // Add fifth and octave for rich resonance
      synth.triggerAttack([frequency * 1.5, frequency * 2], Tone.now() + 0.1);
    }
  } else {
    // For simple tones, just play the frequency with auto-release
    synth.triggerAttackRelease(frequency, duration);
  }
}

/**
 * Stop any playing frequency
 */
function stopFrequency() {
  if (synth) {
    synth.releaseAll();
  }
}

/**
 * Play a completion tone sequence
 */
function playCompletionTone() {
  // Create a sequence of tones based on phi ratios of current frequency
  const baseFreq = currentFrequency;
  
  // Play ascending phi sequence
  setTimeout(() => synth.triggerAttackRelease(baseFreq, 0.2), 0);
  setTimeout(() => synth.triggerAttackRelease(baseFreq * PHI_INVERSE, 0.2), 300);
  setTimeout(() => synth.triggerAttackRelease(baseFreq * 1.0, 0.2), 600);
  setTimeout(() => synth.triggerAttackRelease(baseFreq * PHI, 0.3), 900);
  setTimeout(() => synth.triggerAttackRelease([baseFreq, baseFreq * PHI, baseFreq * PHI_SQUARED], 0.5), 1300);
}

